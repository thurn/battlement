/// Returns the prepared mesh and its remapped face/back materials.
pub fn model(card: CardId) -> PrefabAddress {
  MODELS[card.suit.index() * 13 + card.rank as usize].clone()
}

/// Returns the owned face texture for a visible logical card.
pub fn face(card: CardId) -> TextureAddress {
  FACES[card.suit.index() * 13 + card.rank as usize].clone()
}
